const MAX_GUESSES = 6;
type LetterState = "correct" | "present" | "absent" | "empty";

function getWord(length: number): string {
  const list = WORDS[length];
  return list[Math.floor(Math.random() * list.length)].toLowerCase();
}

function evaluateGuess(guess: string, answer: string): LetterState[] {
  const result: LetterState[] = Array(guess.length).fill("absent");
  const answerArr = answer.split("");
  const guessArr = guess.split("");
  const used = Array(answer.length).fill(false);
  for (let i = 0; i < guess.length; i++) {
    if (guessArr[i] === answerArr[i]) {
      result[i] = "correct";
      used[i] = true;
    }
  }
  for (let i = 0; i < guess.length; i++) {
    if (result[i] === "correct") continue;
    for (let j = 0; j < answer.length; j++) {
      if (!used[j] && guessArr[i] === answerArr[j]) {
        result[i] = "present";
        used[j] = true;
        break;
      }
    }
  }
  return result;
}

const STATE_STYLES: Record<LetterState, string> = {
  correct: "bg-green-500 border-green-500 text-white",
  present: "bg-yellow-500 border-yellow-500 text-white",
  absent: "bg-slate-700 border-slate-700 text-slate-300",
  empty: "bg-transparent border-slate-600 text-slate-200",
};

const KEYBOARD_ROWS = [
  ["q", "w", "e", "r", "t", "y", "u", "i", "o", "p"],
  ["a", "s", "d", "f", "g", "h", "j", "k", "l"],
  ["Enter", "z", "x", "c", "v", "b", "n", "m", "⌫"],
];

export default function Worldle() {
  const [wordLength, setWordLength] = useState(5);
  const [answer, setAnswer] = useState(() => getWord(5));
  const [guesses, setGuesses] = useState<string[]>([]);
  const [evaluations, setEvaluations] = useState<LetterState[][]>([]);
  const [currentInput, setCurrentInput] = useState("");
  const [gameOver, setGameOver] = useState(false);
  const [won, setWon] = useState(false);
  const [error, setError] = useState("");
  const [shake, setShake] = useState(false);

  const letterStatus: Record<string, LetterState> = {};
  for (let gi = 0; gi < guesses.length; gi++) {
    const g = guesses[gi];
    for (let ci = 0; ci < g.length; ci++) {
      const ch = g[ci];
      const prev = letterStatus[ch];
      const cur = evaluations[gi]?.[ci];
      if (!cur) continue;
      if (prev === "correct") continue;
      if (cur === "correct") {
        letterStatus[ch] = "correct";
        continue;
      }
      if (prev === "present") continue;
      letterStatus[ch] = cur;
    }
  }

  const submitGuess = useCallback(
    (
      input: string,
      ans: string,
      gs: string[],
      evals: LetterState[][],
      wl: number,
    ) => {
      if (input.length !== wl) {
        setError(`Word must be ${wl} letters!`);
        setShake(true);
        setTimeout(() => setShake(false), 400);
        return;
      }
      const ev = evaluateGuess(input, ans);
      const newGs = [...gs, input];
      const newEvals = [...evals, ev];
      setGuesses(newGs);
      setEvaluations(newEvals);
      setCurrentInput("");
      setError("");
      if (input === ans) {
        setWon(true);
        setGameOver(true);
      } else if (newGs.length >= MAX_GUESSES) {
        setGameOver(true);
      }
    },
    [],
  );

  const handleKey = useCallback(
    (key: string) => {
      if (gameOver) return;
      if (key === "Backspace" || key === "⌫") {
        setCurrentInput((p) => p.slice(0, -1));
        setError("");
        return;
      }
      if (key === "Enter") {
        submitGuess(currentInput, answer, guesses, evaluations, wordLength);
        return;
      }
      if (/^[a-zA-Z]$/.test(key) && currentInput.length < wordLength) {
        setCurrentInput((p) => p + key.toLowerCase());
        setError("");
      }
    },
    [
      gameOver,
      currentInput,
      answer,
      guesses,
      evaluations,
      wordLength,
      submitGuess,
    ],
  );

  useEffect(() => {
    const handler = (e: KeyboardEvent) => handleKey(e.key);
    window.addEventListener("keydown", handler);
    return () => window.removeEventListener("keydown", handler);
  }, [handleKey]);

  const startNew = (len?: number) => {
    const l = len ?? wordLength;
    setWordLength(l);
    setAnswer(getWord(l));
    setGuesses([]);
    setEvaluations([]);
    setCurrentInput("");
    setGameOver(false);
    setWon(false);
    setError("");
  };

  const rows = Array.from({ length: MAX_GUESSES }, (_, i) => {
    if (i < guesses.length) {
      return {
        letters: guesses[i].split(""),
        states: evaluations[i],
        id: `done-${i}`,
      };
    }
    if (i === guesses.length && !gameOver) {
      const letters = currentInput.split("");
      while (letters.length < wordLength) letters.push("");
      return {
        letters,
        states: Array<LetterState>(wordLength).fill("empty"),
        id: "current",
      };
    }
    return {
      letters: Array<string>(wordLength).fill(""),
      states: Array<LetterState>(wordLength).fill("empty"),
      id: `empty-${i}`,
    };
  });

  return (
    <div className="flex flex-col items-center gap-4 font-mono select-none">
      <p className="text-slate-400 text-sm text-center">
        Guess the hidden word — green = correct spot, yellow = wrong spot.
      </p>

      {/* Word length selector */}
      <div className="flex items-center gap-2 flex-wrap justify-center">
        <span className="text-xs text-slate-400">Word length:</span>
        {[3, 4, 5, 6, 7, 8].map((l) => (
          <button
            key={`len-${l}`}
            type="button"
            onClick={() => startNew(l)}
            className={`px-3 py-1 rounded-lg text-xs border transition-all ${
              wordLength === l && !gameOver
                ? "bg-violet-500 border-violet-500 text-white"
                : "border-slate-600 text-slate-400 hover:border-fuchsia-400 hover:text-fuchsia-300"
            }`}
          >
            {l}
          </button>
        ))}
      </div>

      {/* Grid */}
      <div className="flex flex-col gap-1.5">
        {rows.map((row, _ri) => (
          <div
            key={row.id}
            className={`flex gap-1.5 ${
              row.id === "current" && shake ? "animate-[shake_0.4s_ease]" : ""
            }`}
          >
            {row.letters.map((letter, ci) => (
              <div
                // biome-ignore lint/suspicious/noArrayIndexKey: fixed-size static grid
                key={ci}
                className={`flex items-center justify-center uppercase font-bold rounded-md border-2 transition-all duration-300 ${
                  wordLength <= 5
                    ? "w-11 h-11 text-base"
                    : wordLength === 6
                      ? "w-10 h-10 text-sm"
                      : "w-9 h-9 text-xs"
                } ${STATE_STYLES[row.states[ci]]}`}
              >
                {letter}
              </div>
            ))}
          </div>
        ))}
      </div>

      {error && <p className="text-red-400 text-xs">{error}</p>}

      {gameOver && (
        <div
          className={`text-center py-2 px-4 rounded-xl border ${
            won
              ? "border-green-500/40 bg-green-500/10 text-green-300"
              : "border-red-500/40 bg-red-500/10 text-red-300"
          }`}
        >
          <p className="font-bold text-sm">
            {won
              ? "🎉 You got it!"
              : `😢 The word was: ${answer.toUpperCase()}`}
          </p>
          <button
            type="button"
            onClick={() => startNew()}
            className="mt-2 text-xs px-4 py-1.5 rounded-lg bg-violet-500 text-white hover:bg-fuchsia-400 transition-colors"
          >
            New Word
          </button>
        </div>
      )}

      {/* On-screen keyboard */}
      <div className="flex flex-col gap-1.5 mt-1">
        {KEYBOARD_ROWS.map((row) => (
          <div key={row.join("")} className="flex gap-1 justify-center">
            {row.map((k) => {
              const status = letterStatus[k];
              return (
                <button
                  key={`key-${k}`}
                  type="button"
                  onClick={() => handleKey(k)}
                  className={`${
                    k === "Enter" || k === "⌫" ? "px-2 text-xs" : "w-7"
                  } h-10 rounded text-xs font-bold uppercase border transition-all ${
                    status === "correct"
                      ? "bg-green-500 border-green-500 text-white"
                      : status === "present"
                        ? "bg-yellow-500 border-yellow-500 text-white"
                        : status === "absent"
                          ? "bg-slate-700 border-slate-700 text-slate-500"
                          : "bg-slate-800 border-slate-600 text-slate-300 hover:bg-slate-700"
                  }`}
                >
                  {k}
                </button>
              );
            })}
          </div>
        ))}
      </div>

      <style>{`
        @keyframes shake {
          0%, 100% { transform: translateX(0); }
          20% { transform: translateX(-6px); }
          40% { transform: translateX(6px); }
          60% { transform: translateX(-4px); }
          80% { transform: translateX(4px); }
        }
      `}</style>
    </div>
  );
}
